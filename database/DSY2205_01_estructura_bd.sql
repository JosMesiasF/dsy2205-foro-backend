SET DEFINE OFF;

CREATE TABLE USUARIOS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(100 CHAR) NOT NULL,
    CORREO VARCHAR2(150 CHAR) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(255 CHAR) NOT NULL,
    ROL VARCHAR2(10 CHAR) DEFAULT 'USER' NOT NULL,
    CONSTRAINT CK_USUARIOS_ROL CHECK (ROL IN ('ADMIN', 'USER'))
);

CREATE TABLE CATEGORIAS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(100 CHAR) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR2(250 CHAR)
);

CREATE TABLE TEMAS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    TITULO VARCHAR2(200 CHAR) NOT NULL,
    CONTENIDO VARCHAR2(2000 CHAR) NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    USUARIO_ID NUMBER NOT NULL,
    CATEGORIA_ID NUMBER NOT NULL,
    CONSTRAINT FK_TEMAS_USUARIOS FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS(ID),
    CONSTRAINT FK_TEMAS_CATEGORIAS FOREIGN KEY (CATEGORIA_ID) REFERENCES CATEGORIAS(ID)
);

CREATE TABLE COMENTARIOS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CONTENIDO VARCHAR2(2000 CHAR) NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    USUARIO_ID NUMBER NOT NULL,
    TEMA_ID NUMBER NOT NULL,
    CONSTRAINT FK_COMENTARIOS_USUARIOS FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS(ID),
    CONSTRAINT FK_COMENTARIOS_TEMAS FOREIGN KEY (TEMA_ID) REFERENCES TEMAS(ID)
);

